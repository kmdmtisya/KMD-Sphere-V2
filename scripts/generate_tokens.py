"""Generate the WealthSphere design tokens for mobile and web from one source (P14-T03).

Source: design/tokens/wealthsphere.tokens.json.
Outputs:
- mobile/wealthsphere_app/lib/shared/design_system/tokens/brand_palette.dart (Dart BrandPalette);
- web/src/tokens/tokens.css (CSS variables for Light, Dark and System, docs/web/WEB_THEME_SYSTEM.md).

The generator validates the source (every role and series names a palette entry; light and dark
define the same roles) and measures WCAG 2.x contrast for the web role pairs: text at least 4.5:1,
icons, borders, focus and chart series at least 3:1. The mobile roles keep their own contrast test
(test/shared/design_system/tokens/contrast_test.dart) and a sync test against this file.

Usage:
    python scripts/generate_tokens.py           # write the outputs
    python scripts/generate_tokens.py --check   # fail if an output is out of date (CI)
"""

from __future__ import annotations

import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "tokens" / "wealthsphere.tokens.json"
DART_OUT = ROOT / "mobile/wealthsphere_app/lib/shared/design_system/tokens/brand_palette.dart"
CSS_OUT = ROOT / "web/src/tokens/tokens.css"

HEX = re.compile(r"^#[0-9A-F]{6}$")
THEMES = ("light", "dark")
GENERATED = "Generated by scripts/generate_tokens.py from design/tokens/wealthsphere.tokens.json."
DO_NOT_EDIT = "Do not edit by hand: edit the token file and run the generator (P14-T03)."

# WCAG pairs measured for the web roles (the same roles and thresholds as the mobile test).
TEXT_ROLES = (
    "textPrimary",
    "textMuted",
    "positiveText",
    "negativeText",
    "warningText",
    "riskLow",
    "riskMedium",
    "riskHigh",
    "primary",
)
SURFACES = ("scaffold", "surface", "surfaceElevated")
ON_PAIRS = (
    ("onPrimary", "primary"),
    ("onAccent", "accent"),
    ("onDemoBadge", "demoBadge"),
    ("onStaleBanner", "staleBanner"),
    ("onTooltip", "tooltipSurface"),
)
NON_TEXT_ROLES = ("border", "positive", "negative", "warning", "focus", "chartGrowth", "chartContributions")
AA_TEXT = 4.5
AA_NON_TEXT = 3.0


class TokenError(ValueError):
    """The token source is invalid."""


def load(path: Path = SOURCE) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def palette_of(tokens: dict) -> dict[str, dict]:
    return {k: v for k, v in tokens["palette"].items() if not k.startswith("$")}


def validate(tokens: dict) -> None:
    palette = palette_of(tokens)
    groups = tokens["palette"]["$groups"]
    for name, entry in palette.items():
        if not HEX.match(entry["value"]):
            raise TokenError(f"palette.{name}: {entry['value']!r} is not #RRGGBB (upper case)")
        if entry.get("group") not in groups:
            raise TokenError(f"palette.{name}: unknown group {entry.get('group')!r}")
    light, dark = (
        {k for k in tokens["roles"][t] if not k.startswith("$")} for t in THEMES
    )
    if light != dark:
        raise TokenError(f"roles: light and dark differ: {sorted(light ^ dark)}")
    for theme in THEMES:
        for role, ref in tokens["roles"][theme].items():
            if ref not in palette:
                raise TokenError(f"roles.{theme}.{role}: unknown palette entry {ref!r}")
        series = tokens["chartSeries"][theme]
        if len(series) < 6 or any(ref not in palette for ref in series):
            raise TokenError(f"chartSeries.{theme}: needs at least six known palette entries")
    for name, spec in tokens["webRoles"].items():
        if name.startswith("$"):
            continue
        refs = [spec] if isinstance(spec, str) else [spec[t] for t in THEMES]
        for ref in refs:
            if ref not in palette and ref not in light:
                raise TokenError(f"webRoles.{name}: {ref!r} is neither a role nor a palette entry")


def resolve(tokens: dict, theme: str) -> dict[str, str]:
    """Every role (mobile roles plus web roles) as a hex value for one theme."""
    palette = palette_of(tokens)
    roles = {k: palette[v]["value"] for k, v in tokens["roles"][theme].items() if not k.startswith("$")}
    for name, spec in tokens["webRoles"].items():
        if name.startswith("$"):
            continue
        ref = spec if isinstance(spec, str) else spec[theme]
        roles[name] = roles[ref] if ref in roles else palette[ref]["value"]
    for i, ref in enumerate(tokens["chartSeries"][theme], start=1):
        roles[f"series{i}"] = palette[ref]["value"]
    return roles


def luminance(hex_colour: str) -> float:
    def channel(c: int) -> float:
        s = c / 255
        return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex_colour[i : i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def contrast_report(tokens: dict) -> list[str]:
    """Every failing web pair, as text (empty when all pass)."""
    failures: list[str] = []
    for theme in THEMES:
        r = resolve(tokens, theme)
        checks: list[tuple[str, str, float]] = []
        checks += [(t, s, AA_TEXT) for t in TEXT_ROLES for s in SURFACES]
        checks += [(fg, bg, AA_TEXT) for fg, bg in ON_PAIRS]
        checks += [(n, "surface", AA_NON_TEXT) for n in NON_TEXT_ROLES]
        series = [k for k in r if k.startswith("series")]
        checks += [(n, "surface", AA_NON_TEXT) for n in series]
        for fg, bg, minimum in checks:
            ratio = contrast(r[fg], r[bg])
            if ratio < minimum:
                failures.append(f"{theme}: {fg} on {bg} is {ratio:.2f}:1 (needs {minimum}:1)")
    return failures


def kebab(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", name).lower()


def dart_comment(text: str, indent: str = "  ", prefix: str = "// ") -> list[str]:
    return [f"{indent}{prefix}{line}" for line in textwrap.wrap(text, width=96 - len(indent) - len(prefix))]


def render_dart(tokens: dict) -> str:
    palette = palette_of(tokens)
    groups = tokens["palette"]["$groups"]
    out = [
        f"// {GENERATED}",
        f"// {DO_NOT_EDIT}",
        "import 'package:flutter/painting.dart';",
        "",
        "/// Raw colour values. **This is the only file allowed to contain colour literals**",
        "/// (enforced by `test/guards/style_guard_test.dart`). Widgets never use these directly: they read",
        "/// semantic roles from `WealthColors`, which map brand values to roles with checked contrast.",
        "abstract final class BrandPalette {",
    ]
    for gi, (group, description) in enumerate(groups.items()):
        if gi:
            out.append("")
        out += dart_comment(f"---- {description}")
        for name, entry in palette.items():
            if entry["group"] != group:
                continue
            if "note" in entry:
                # dart format separates a doc comment from a preceding declaration.
                if out[-1].lstrip().startswith("static const"):
                    out.append("")
                out.append(f"  /// {entry['note']}")
            out.append(f"  static const Color {name} = Color(0xFF{entry['value'][1:]});")
    out.append("}")
    return "\n".join(out) + "\n"


def css_block(selector: str, roles: dict[str, str], scheme: str, indent: str = "") -> list[str]:
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  --ws-{kebab(name)}: {value};" for name, value in roles.items()]
    lines += [f"{indent}  color-scheme: {scheme};", f"{indent}}}"]
    return lines


def render_css(tokens: dict) -> str:
    light, dark = resolve(tokens, "light"), resolve(tokens, "dark")
    scale = tokens["scale"]
    out = [
        f"/* {GENERATED}",
        f" * {DO_NOT_EDIT}",
        " * Themes (docs/web/WEB_THEME_SYSTEM.md): the server sets data-theme-pref on <html>; \"system\"",
        " * follows prefers-color-scheme in CSS alone, so the first paint is right without JavaScript. */",
        "",
    ]
    out += css_block(':root,\n[data-theme-pref="light"]', light, "light")
    out.append("")
    out += css_block('[data-theme-pref="dark"]', dark, "dark")
    out += ["", "@media (prefers-color-scheme: dark) {"]
    out += css_block('[data-theme-pref="system"]', dark, "dark", indent="  ")
    out += ["}", "", ":root {"]
    out += [f"  --ws-space-{k}: {v}px;" for k, v in scale["spacing"].items()]
    out += [f"  --ws-radius-{k}: {v}px;" for k, v in scale["radius"]["web"].items()]
    out += [f"  --ws-font-size-{kebab(k.replace('Size', ''))}: {v}px;" for k, v in scale["type"]["web"].items()]
    out += [
        f"  --ws-motion-fast: {scale['motion']['fastMs']}ms;",
        f"  --ws-motion-standard: {scale['motion']['standardMs']}ms;",
        "}",
        "",
        "@media (prefers-reduced-motion: reduce) {",
        "  :root {",
        "    --ws-motion-fast: 0ms;",
        "    --ws-motion-standard: 0ms;",
        "  }",
        "}",
    ]
    return "\n".join(out) + "\n"


def outputs(tokens: dict) -> dict[Path, str]:
    return {DART_OUT: render_dart(tokens), CSS_OUT: render_css(tokens)}


def main(argv: list[str]) -> int:
    tokens = load()
    try:
        validate(tokens)
    except TokenError as error:
        print(f"invalid token source: {error}", file=sys.stderr)
        return 1
    failures = contrast_report(tokens)
    if failures:
        print("contrast below WCAG AA:\n  " + "\n  ".join(failures), file=sys.stderr)
        return 1
    stale = []
    for path, content in outputs(tokens).items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current == content:
            continue
        if "--check" in argv:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("out of date, run `python scripts/generate_tokens.py`: " + ", ".join(stale), file=sys.stderr)
        return 1
    if "--check" in argv:
        print("design tokens: outputs match the source; contrast passes in light and dark")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
