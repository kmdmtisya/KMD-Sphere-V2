"""Writes reports/quality/qg-15-forex-model-validation.md (P13-T05, QG-15): the forecasting
framework run on controlled synthetic processes and on the simulated feed. Deterministic (fixed
seeds). No real market data exists yet (DEC-19), so this validates the framework, not any edge.

    cd backend && uv run python ../scripts/forex_model_report.py
"""

import asyncio
import sys
from datetime import UTC, datetime, timedelta
from decimal import Decimal
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.modules.forex.candles.aggregate import aggregate  # noqa: E402
from app.modules.forex.forecast import drift, pipeline  # noqa: E402
from app.modules.forex.forecast import features as feat  # noqa: E402
from app.modules.forex.forecast import models as mdl  # noqa: E402
from app.modules.forex.forecast.evaluation import (  # noqa: E402
    Evaluation,
    evaluate,
    leakage_audit,
    walk_forward,
)
from app.modules.forex.marketdata.fake import FakeForexProvider  # noqa: E402
from app.modules.forex.marketdata.types import Timeframe  # noqa: E402

OUT = ROOT / "reports" / "quality" / "qg-15-forex-model-validation.md"
D = Decimal


def returns(n: int, phi: float, seed: int, scale: float = 1e-3) -> np.ndarray:
    rng = np.random.default_rng(seed)
    r = np.zeros(n)
    for t in range(1, n):
        r[t] = phi * r[t - 1] + rng.normal(0, scale)
    return r


def series_from(r: np.ndarray) -> pipeline.Series:
    c = 1.1 * np.exp(np.cumsum(r))
    ts = [datetime(2026, 1, 5, tzinfo=UTC) + timedelta(hours=k) for k in range(len(r))]
    return pipeline.Series(
        ts,
        [D(f"{v:.5f}") for v in c],
        [D(f"{v * 1.0004:.5f}") for v in c],
        [D(f"{v * 0.9996:.5f}") for v in c],
    )


def table(ev: Evaluation) -> list[str]:
    lines = [
        "| Model | Family | Log loss | Brier | Direction | Cover 50% | Cover 80% | CRPS (approx.) | vs random walk (DM p) | Edge | Probability | Calibration (ECE) |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in ev.results:
        if r.error:
            lines.append(f"| {r.name} | {r.family} | error: {r.error} | | | | | | | | | |")
            continue
        m = r.metrics
        rw = r.versus.get("random_walk")
        vs = "—" if rw is None else f"{rw['log_loss_difference']:+.4f} (p {rw['dm_p_value']:.3f})"
        c = r.calibration
        cal = "—" if c is None else f"{c.status} ({c.ece_calibrated:.3f})"
        lines.append(
            f"| {r.name} | {r.family} | {m['log_loss']:.4f} | {m['brier']:.4f} | {m['direction_accuracy']:.3f} | "
            f"{m['coverage_50']:.3f} | {m['coverage_80']:.3f} | {m['crps_approx']:.6f} | {vs} | "
            f"{'yes' if r.edge else 'no'} | {r.probability} | {cal} |"
        )
    return lines


def simulated_feed() -> pipeline.Run:
    now = datetime(2026, 10, 8, 20, 0, tzinfo=UTC)
    provider = FakeForexProvider(clock=lambda: now)
    minutes = asyncio.run(
        provider.candles("EUR_USD", Timeframe.M1, now - timedelta(days=3, hours=4), now)
    )
    bars = [c for c in aggregate(minutes, Timeframe.M5, now).candles if not c.forming]
    s = pipeline.Series(
        [b.ts for b in bars], [b.close for b in bars], [b.high for b in bars], [b.low for b in bars]
    )
    return pipeline.run(s, "15m", 5)


def main() -> None:
    lines = [
        "# QG-15 evidence: forex forecasting framework validation (P13-T05)",
        "",
        "_Generated by `scripts/forex_model_report.py` (deterministic: fixed seeds). The method is in_",
        "_docs/design/forex-forecasting.md; the tests are in backend/tests/forex/test_forecast_core.py and test_forecast_api.py._",
        "",
        "**Read this first.** No real market data is used: the forex provider is fixture-only (DEC-19). These runs check that",
        "the framework behaves correctly on processes whose answer is known: it finds no edge where none exists, finds the",
        "edge where one does, never sees the future, measures calibration and interval coverage, and flags drift. They say",
        "nothing about whether any model can forecast real currency markets. That needs licensed data and a fresh evaluation.",
        "",
    ]

    # 1. Random walk: no model should show an edge.
    rw_run = pipeline.run(series_from(returns(1500, 0.0, 3)), "4h", 5)
    lines += [
        "## 1. Random walk (no edge exists): QG-15.1, QG-15.3",
        "",
        f"1,500 hourly bars of a pure random walk, horizon 4h (4 bars), {rw_run.evaluation.folds} expanding walk-forward folds,",
        f"{rw_run.evaluation.test_rows} out-of-sample test bars, purge gaps of 4 bars. Every model is compared with every baseline.",
        "",
        *table(rw_run.evaluation),
        "",
        f"**Outcome:** no model shows a demonstrated edge; the published forecast is the **{rw_run.published.model}** baseline",
        '("no demonstrated edge"), as the rules require.',
        "",
    ]

    # 2. Positive control: a predictable process.
    r = returns(1500, 0.5, 5)
    h = 1
    y = np.full(len(r), np.nan)
    y[:-h] = r[1:]
    r1 = r.copy()
    r1[0] = np.nan
    ctx = mdl.Context(r[:, None], y, r1, h)
    folds = walk_forward(np.arange(1, len(r) - h, dtype=np.int64), h, initial=700, test_size=200)
    pos = evaluate(
        {
            "arima": mdl.Arima,
            "lightgbm": lambda: mdl.TreeModel("lightgbm", 7),
            "random_forest": lambda: mdl.TreeModel("random_forest", 7),
        },
        pipeline.BASELINE_FACTORIES,
        ctx,
        folds,
    )
    lines += [
        "## 2. Positive control: returns with autocorrelation 0.5, horizon 1 bar",
        "",
        *table(pos),
        "",
        "**Outcome:** the framework finds the edge that exists (Diebold-Mariano p < 0.05 against every baseline).",
        "",
    ]

    # 3. Leakage.
    lctx_s = series_from(returns(900, 0.3, 3))
    m = feat.build(lctx_s.close, lctx_s.high, lctx_s.low)
    lctx = mdl.Context(m.x, feat.labels(lctx_s.close, 4), m.r1, 4)
    rows = np.flatnonzero(np.isfinite(lctx.x).all(axis=1) & np.isfinite(lctx.y)).astype(np.int64)
    fold = walk_forward(rows, 4, initial=500, test_size=100)[0]

    class Leaky:
        name, family, params = "leaky (uses the label)", "test", {}

        def fit(self, c: mdl.Context, a: np.ndarray, b: np.ndarray) -> None:
            return None

        def predict(self, c: mdl.Context, idx: np.ndarray) -> mdl.Distribution:
            return mdl.gaussian(np.nan_to_num(c.y[idx]), np.full(len(idx), 1e-3))

    audits = {
        "no_change": mdl.NoChange,
        "random_walk": mdl.RandomWalk,
        "drift": mdl.Drift,
        "arima": mdl.Arima,
        "random_forest": lambda: mdl.TreeModel("random_forest", 7),
        "lightgbm": lambda: mdl.TreeModel("lightgbm", 7),
        "xgboost": lambda: mdl.TreeModel("xgboost", 7),
        "leaky (deliberate)": Leaky,
    }
    lines += [
        "## 3. Leakage audit: QG-15.2",
        "",
        "For three test origins per model, everything unknown at prediction time (later features and returns, and labels",
        "that use later closes) is replaced with noise; the prediction must not change. Splits are purged (checked on every",
        "fold) and features are rebuilt on every prefix in the tests.",
        "",
        "| Model | Passes |",
        "|---|---|",
        *[
            f"| {name} | {'yes' if leakage_audit(make, lctx, fold) else '**no (leak detected)**'} |"
            for name, make in audits.items()
        ],
        "",
    ]

    # 4. Intervals.
    ar = returns(1600, 0.4, 11)
    hh = 4
    yy = np.full(len(ar), np.nan)
    yy[:-hh] = [ar[t + 1 : t + 1 + hh].sum() for t in range(len(ar) - hh)]
    rr = ar.copy()
    rr[0] = np.nan
    actx = mdl.Context(ar[:, None], yy, rr, hh)
    arima = mdl.Arima()
    arima.fit(actx, np.arange(1, 800, dtype=np.int64), np.arange(800, 900, dtype=np.int64))
    origins = np.arange(900, 1590, dtype=np.int64)
    d = arima.predict(actx, origins)
    c80 = float(np.mean((yy[origins] >= d.quantiles[:, 0]) & (yy[origins] <= d.quantiles[:, 4])))
    c50 = float(np.mean((yy[origins] >= d.quantiles[:, 1]) & (yy[origins] <= d.quantiles[:, 3])))
    lines += [
        "## 4. Interval coverage: QG-15.5",
        "",
        "ARIMA on returns with autocorrelation 0.4, horizon 4 bars, 690 out-of-sample origins (exact ARMA cumulative variance):",
        "",
        "| Nominal | Empirical coverage |",
        "|---|---|",
        f"| 50% | {c50:.3f} |",
        f"| 80% | {c80:.3f} |",
        "",
        f"Coverage is {100 * (0.8 - c80):.1f} points below nominal at 80% and {100 * (0.5 - c50):.1f} at 50%: the interval",
        "ignores the uncertainty of the estimated parameters, so it is somewhat too narrow. It is reported, not corrected.",
        "Every evaluation table above also reports each model's 50% and 80% coverage.",
        "",
    ]

    # 5. Calibration and drift.
    s = series_from(returns(1500, 0.0, 8))
    mm = feat.build(s.close, s.high, s.low)
    stationary = drift.check(mm.names, mm.x[100:1100], mm.x[1300:])
    calm = returns(1500, 0.0, 8)
    wild = np.r_[calm[:1100], calm[1100:] * 4]
    w = series_from(wild)
    mw = feat.build(w.close, w.high, w.low)
    shifted = drift.check(mw.names, mw.x[100:1000], mw.x[1300:])
    lines += [
        "## 5. Calibration and drift: QG-15.4, QG-15.6",
        "",
        "Calibration is measured for every model in the tables above (expected calibration error on held-out bars after",
        'recalibration on separate calibration windows, used only when it helps). A probability is labelled "Requires',
        'calibration" unless at least 300 held-out bars give ECE ≤ 0.05 and no bin of 20 or more is off by more than 0.10.',
        "",
        "| Drift scenario | Status | Reasons |",
        "|---|---|---|",
        f"| Stationary random walk | {stationary.status} | {'; '.join(stationary.reasons) or '—'} |",
        f"| Volatility quadruples after bar 1,100 | {shifted.status} | {'; '.join(shifted.reasons) or '—'} |",
        "",
        "The hourly training job checks drift for every published model; a breach disables the pair's forecasts until",
        "retraining is approved (`store.approve_retraining`).",
        "",
    ]

    # 6. Volatility and the simulated feed.
    sim = simulated_feed()
    lines += [
        "## 6. Volatility models",
        "",
        f"Random walk run (section 1): EWMA RMSE {rw_run.volatility['ewma_rmse']:.6f}; HAR RMSE {rw_run.volatility.get('har_rmse', float('nan')):.6f}; chosen: {rw_run.published.volatility_model}.",
        "",
        "## 7. The simulated feed (development data, not a market)",
        "",
        "Three trading days of the simulated provider's EUR_USD minutes, aggregated to 5-minute bars, horizon 15m. The",
        "simulator moves the price on a daily wave with hashed noise, so any edge found here is an artefact of the",
        "simulator and says nothing about real markets. Forecasts from it are labelled `simulated` end to end.",
        "",
        *table(sim.evaluation),
        "",
        f"Published: **{sim.published.model}** (edge: {'yes' if sim.published.edge else 'no'}); drift: {sim.drift.status}.",
        'The API states every edge on simulated data as "on simulated data: not evidence about real markets".',
        "",
        "## 8. Open items",
        "",
        "- A real evaluation needs licensed market data (DEC-19); these results must be regenerated then and reviewed.",
        "- GARCH-family volatility models and SARIMA seasonality are not in v1 (EWMA and HAR are); LSTM, GRU and",
        "  Transformer models are research-only (DEC-22).",
        "- CRPS is approximated from five quantiles; the ARIMA interval ignores parameter uncertainty.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
