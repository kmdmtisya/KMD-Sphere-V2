export type Capabilities = { forex: boolean; support: boolean };

export function visibleNav(capabilities: Capabilities): NavGroup[] {
  const allowed = (r?: "forex" | "support") => !r || capabilities[r];
  return NAV.filter((g) => allowed(g.requires)).map((g) => ({ ...g, items: g.items.filter((i) => allowed(i.requires)) }));
}

export function findNavItem(href: string): NavItem | undefined {
  return NAV.flatMap((g) => g.items).find((i) => i.href === href);
}

/** The nav item whose route is the longest prefix of `pathname` (for the active marker). */
export function activeItem(pathname: string, items: NavItem[]): NavItem | undefined {
  return [...items]
    .filter((i) => pathname === i.href || pathname.startsWith(`${i.href}/`))
    .sort((a, b) => b.href.length - a.href.length)[0];
}
